#!/usr/bin/env bash
# Generate web/index.html: the standalone viewer page (document skeleton + web/viewer.html).
# web/viewer.html is the source, written as an artifact page body (the claude.ai host adds the
# skeleton when it is published); edit that file, not index.html.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
{
  printf '%s\n' '<!doctype html>' '<!-- Generated by scripts/build_web.sh from web/viewer.html; do not edit. -->' \
    '<html lang="en"><head><meta charset="utf-8">' \
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">' \
    '<style>:root{color-scheme:light}body{margin:0;font:14px system-ui,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>' \
    '</head><body>'
  cat "$ROOT/web/viewer.html"
  printf '%s\n' '</body></html>'
} > "$ROOT/web/index.html"
echo "$ROOT/web/index.html"
